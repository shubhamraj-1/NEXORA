-- NEXORA Supabase schema.
-- Run once in Supabase SQL Editor or with the Supabase CLI. Free Plan compatible.
-- Service role writes from FastAPI are trusted; client access is protected by RLS.

create extension if not exists pgcrypto;

-- Profiles -------------------------------------------------------------------
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  display_name text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Runs -----------------------------------------------------------------------
create table if not exists public.runs (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  url text not null,
  instruction text not null default '',
  title text,
  answer text,
  plan jsonb not null default '[]'::jsonb,
  model text,
  status_code integer,
  elapsed_ms integer not null default 0,
  result jsonb,
  created_at timestamptz not null default now()
);

create index if not exists runs_user_created_idx
  on public.runs (user_id, created_at desc);

-- Tasks ----------------------------------------------------------------------
create table if not exists public.tasks (
  id text primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  status text not null check (
    status in ('queued', 'running', 'succeeded', 'failed', 'cancelled')
  ),
  progress integer not null default 0,
  url text not null,
  instruction text not null default '',
  error text,
  created_at timestamptz not null,
  updated_at timestamptz not null
);

create index if not exists tasks_user_updated_idx
  on public.tasks (user_id, updated_at desc);

-- Task logs ------------------------------------------------------------------
create table if not exists public.task_logs (
  id bigint generated by default as identity primary key,
  task_id text not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  timestamp timestamptz not null,
  level text not null default 'info',
  message text not null
);

create index if not exists task_logs_task_time_idx
  on public.task_logs (task_id, timestamp asc);

-- Task results ---------------------------------------------------------------
create table if not exists public.task_results (
  task_id text primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  result jsonb not null default '{}'::jsonb,
  saved_at timestamptz not null default now()
);

-- Automatic profile creation -------------------------------------------------
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, display_name)
  values (
    new.id,
    new.email,
    new.raw_user_meta_data ->> 'display_name'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Row Level Security ---------------------------------------------------------
alter table public.profiles enable row level security;
alter table public.runs enable row level security;
alter table public.tasks enable row level security;
alter table public.task_logs enable row level security;
alter table public.task_results enable row level security;

drop policy if exists "profiles own" on public.profiles;
create policy "profiles own"
  on public.profiles for all
  using (auth.uid() = id)
  with check (auth.uid() = id);

drop policy if exists "runs own" on public.runs;
create policy "runs own"
  on public.runs for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists "tasks own" on public.tasks;
create policy "tasks own"
  on public.tasks for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists "task logs own" on public.task_logs;
create policy "task logs own"
  on public.task_logs for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists "task results own" on public.task_results;
create policy "task results own"
  on public.task_results for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

-- Private Storage bucket for generated screenshots --------------------------
insert into storage.buckets (id, name, public)
values ('generated-files', 'generated-files', false)
on conflict (id) do nothing;

drop policy if exists "generated files select own" on storage.objects;
create policy "generated files select own"
  on storage.objects for select
  using (
    bucket_id = 'generated-files'
    and (storage.foldername(name))[1] = auth.uid()::text
  );

drop policy if exists "generated files insert own" on storage.objects;
create policy "generated files insert own"
  on storage.objects for insert
  with check (
    bucket_id = 'generated-files'
    and (storage.foldername(name))[1] = auth.uid()::text
  );

drop policy if exists "generated files update own" on storage.objects;
create policy "generated files update own"
  on storage.objects for update
  using (
    bucket_id = 'generated-files'
    and (storage.foldername(name))[1] = auth.uid()::text
  )
  with check (
    bucket_id = 'generated-files'
    and (storage.foldername(name))[1] = auth.uid()::text
  );

drop policy if exists "generated files delete own" on storage.objects;
create policy "generated files delete own"
  on storage.objects for delete
  using (
    bucket_id = 'generated-files'
    and (storage.foldername(name))[1] = auth.uid()::text
  );
